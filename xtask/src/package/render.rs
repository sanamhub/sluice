//! The four formats, as text. Each names the release's own URLs and hashes, so a maintainer copies a
//! file and never retypes a checksum.

use anyhow::Result;

use super::{Checksums, DESCRIPTION, HOMEPAGE, LICENSE, PUBLISHER, SHORT, TARGETS, url};

/// The hash of `triple`'s artifact in `sums`.
fn sum<'a>(sums: &'a Checksums, triple: &str) -> Result<&'a str> {
    let target = TARGETS
        .iter()
        .find(|target| target.triple == triple)
        .expect("every triple named here is a target");
    sums.get(&target.artifact())
        .map(String::as_str)
        .ok_or_else(|| anyhow::anyhow!("no checksum for {}", target.artifact()))
}

/// The release URL of `triple`'s artifact.
fn shipped(version: &str, triple: &str) -> String {
    let target = TARGETS
        .iter()
        .find(|target| target.triple == triple)
        .expect("every triple named here is a target");
    url(version, &target.artifact())
}

/// A Homebrew formula for the four Unix targets.
pub fn formula(version: &str, sums: &Checksums) -> Result<String> {
    let mac_arm = sum(sums, "aarch64-apple-darwin")?;
    let mac_intel = sum(sums, "x86_64-apple-darwin")?;
    let linux_arm = sum(sums, "aarch64-unknown-linux-gnu")?;
    let linux_intel = sum(sums, "x86_64-unknown-linux-gnu")?;
    let mac_arm_url = shipped(version, "aarch64-apple-darwin");
    let mac_intel_url = shipped(version, "x86_64-apple-darwin");
    let linux_arm_url = shipped(version, "aarch64-unknown-linux-gnu");
    let linux_intel_url = shipped(version, "x86_64-unknown-linux-gnu");
    Ok(format!(
        r##"# Generated by `cargo xtask package {version}`. Do not edit: run the generator again.
class Sluice < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "{mac_arm_url}"
      sha256 "{mac_arm}"
    end

    on_intel do
      url "{mac_intel_url}"
      sha256 "{mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "{linux_arm_url}"
      sha256 "{linux_arm}"
    end

    on_intel do
      url "{linux_intel_url}"
      sha256 "{linux_intel}"
    end
  end

  def install
    bin.install Dir["*/sluice"].first
  end

  test do
    system "#{{bin}}/sluice", "--version"
  end
end
"##
    ))
}

/// A Scoop manifest for the two Windows targets.
pub fn scoop(version: &str, sums: &Checksums) -> Result<String> {
    let x64 = sum(sums, "x86_64-pc-windows-msvc")?;
    let arm = sum(sums, "aarch64-pc-windows-msvc")?;
    let x64_url = shipped(version, "x86_64-pc-windows-msvc");
    let arm_url = shipped(version, "aarch64-pc-windows-msvc");
    Ok(format!(
        r#"{{
  "version": "{version}",
  "description": "{DESCRIPTION}",
  "homepage": "{HOMEPAGE}",
  "license": "{LICENSE}",
  "architecture": {{
    "64bit": {{
      "url": "{x64_url}",
      "hash": "{x64}",
      "bin": "sluice-cli-x86_64-pc-windows-msvc/sluice.exe"
    }},
    "arm64": {{
      "url": "{arm_url}",
      "hash": "{arm}",
      "bin": "sluice-cli-aarch64-pc-windows-msvc/sluice.exe"
    }}
  }},
  "checkver": {{
    "github": "{HOMEPAGE}"
  }},
  "autoupdate": {{
    "architecture": {{
      "64bit": {{ "url": "{HOMEPAGE}/releases/download/v$version/sluice-cli-x86_64-pc-windows-msvc.zip" }},
      "arm64": {{ "url": "{HOMEPAGE}/releases/download/v$version/sluice-cli-aarch64-pc-windows-msvc.zip" }}
    }}
  }}
}}
"#
    ))
}

/// The winget version manifest, which names the package and the release.
pub fn winget_version(version: &str) -> String {
    format!(
        "# Generated by `cargo xtask package {version}`. Do not edit: run the generator again.\n\
PackageIdentifier: {PUBLISHER}.sluice\n\
PackageVersion: {version}\n\
DefaultLocale: en-US\n\
ManifestType: version\n\
ManifestVersion: 1.6.0\n"
    )
}

/// The winget installer manifest: the two zips, each with the `sluice.exe` inside it.
pub fn winget_installer(version: &str, sums: &Checksums) -> Result<String> {
    let x64 = sum(sums, "x86_64-pc-windows-msvc")?.to_ascii_uppercase();
    let arm = sum(sums, "aarch64-pc-windows-msvc")?.to_ascii_uppercase();
    let x64_url = shipped(version, "x86_64-pc-windows-msvc");
    let arm_url = shipped(version, "aarch64-pc-windows-msvc");
    Ok(format!(
        r#"# Generated by `cargo xtask package {version}`. Do not edit: run the generator again.
PackageIdentifier: {PUBLISHER}.sluice
PackageVersion: {version}
InstallerType: zip
NestedInstallerType: portable
Installers:
  - Architecture: x64
    InstallerUrl: {x64_url}
    InstallerSha256: {x64}
    NestedInstallerFiles:
      - RelativeFilePath: sluice-cli-x86_64-pc-windows-msvc/sluice.exe
        PortableCommandAlias: sluice
  - Architecture: arm64
    InstallerUrl: {arm_url}
    InstallerSha256: {arm}
    NestedInstallerFiles:
      - RelativeFilePath: sluice-cli-aarch64-pc-windows-msvc/sluice.exe
        PortableCommandAlias: sluice
ManifestType: installer
ManifestVersion: 1.6.0
"#
    ))
}

