/// An AUR `PKGBUILD` for a binary package of the two Linux targets.
pub fn pkgbuild(version: &str, sums: &Checksums) -> Result<String> {
    let x64 = sum(sums, "x86_64-unknown-linux-gnu")?;
    let arm = sum(sums, "aarch64-unknown-linux-gnu")?;
    let x64_url = shipped(version, "x86_64-unknown-linux-gnu");
    let arm_url = shipped(version, "aarch64-unknown-linux-gnu");
    let x64_folder = folder("x86_64-unknown-linux-gnu");
    let arm_folder = folder("aarch64-unknown-linux-gnu");
    // `makepkg` refuses a hyphen in `pkgver`, which a pre-release version has. The hyphen is
    // removed rather than replaced with a separator: pacman's `vercmp` reads a separator followed
    // by more text as newer, so `1.3.0_rc.2` would sort above `1.3.0` and upgrading from the
    // release candidate to the release would be a downgrade. `1.3.0rc.2` sorts below `1.3.0`, and
    // the source URL keeps the version as the tag spells it.
    let pkgver = pkgver(version);
    Ok(format!(
        r#"# Generated by `cargo xtask package {version}`. Do not edit: run the generator again.
pkgname=sluice-bin
pkgver={pkgver}
pkgrel=1
pkgdesc='{DESCRIPTION}'
arch=('x86_64' 'aarch64')
url="{HOMEPAGE}"
license=('MIT' 'Apache-2.0')
provides=('sluice')
conflicts=('sluice')
options=('!strip')
source_x86_64=("{x64_url}")
sha256sums_x86_64=('{x64}')
source_aarch64=("{arm_url}")
sha256sums_aarch64=('{arm}')

package() {{
  case "$CARCH" in
    x86_64) _folder={x64_folder} ;;
    aarch64) _folder={arm_folder} ;;
  esac
  install -Dm755 "$srcdir/$_folder/sluice" "$pkgdir/usr/bin/sluice"
}}
"#
    ))
}

/// The `pkgver` for `version`. `makepkg` refuses a hyphen in it, and the hyphen is removed rather
/// than replaced with a separator because of the order pacman gives: a separator followed by more
/// text is newer, so `1.3.0_rc.2` compares above `1.3.0`. Without the hyphen, `1.3.0rc.2` compares
/// below `1.3.0`, so the release candidate is what a package upgrades from.
pub(super) fn pkgver(version: &str) -> String {
    version.replace('-', "")
}

/// The folder `triple`'s archive unpacks to.
fn folder(triple: &str) -> String {
    target(triple).folder()
}
